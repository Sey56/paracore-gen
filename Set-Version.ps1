<#
.SYNOPSIS
    Set / check / show THIS repo's version.

.DESCRIPTION
    Each sibling MCP repo versions ITSELF, on its own schedule. This script is
    the whole mechanism: bump `VERSION`, and the repo's own `build-*.ps1` picks
    it up and hands it to the installer.

    `VERSION` (this folder) is the AUTHORITY. `version-info.txt` is GENERATED by
    the build - never edit it. `pyproject.toml` and this project's own entry in
    `uv.lock` are the only other places the number is stored, and this script
    keeps them in step.

    NOTE: `paracore` (the engine + add-in) versions as ONE unit and has its own
    script, `paracore/scripts/Set-Version.ps1`. It is never touched from here.

    IMPORTANT: keep this file ASCII-ONLY. Windows PowerShell 5.1 decodes a
    BOM-less .ps1 as ANSI, so a non-ASCII character inside a string mojibakes
    into a smart-quote, which PowerShell treats as a string delimiter, and the
    script fails to parse with a misleading "Missing closing '}'". Comments are
    safe; STRINGS are not.

.PARAMETER Version
    MAJOR.MINOR.PATCH. Defaults to the current `VERSION`.

.PARAMETER Check
    Verify every surface equals `VERSION`. Writes NOTHING. Exit 1 on mismatch.

.PARAMETER Show
    Print the current value of every surface. Writes nothing.

.PARAMETER Commit
    `git add` exactly the files this script owns, then commit them.
    Never `git add -A`.

.EXAMPLE
    ./Set-Version.ps1 2.0.0
.EXAMPLE
    ./Set-Version.ps1 -Check
.EXAMPLE
    ./Set-Version.ps1 -Show
#>

[CmdletBinding()]
param(
    [Parameter(Position = 0)][string]$Version = "",
    [switch]$Check,
    [switch]$Show,
    [switch]$Commit
)

$ErrorActionPreference = 'Stop'

$Root     = $PSScriptRoot
$RepoName = Split-Path $Root -Leaf
# CAUTION: read AND write every surface as UTF-8 with NO BOM.
#   `Get-Content -Raw` with no -Encoding decodes a BOM-less file with the ANSI
#   code page, so writing the result back as UTF-8 double-encodes every
#   non-ASCII character: an em-dash in a comment returned as three mojibake
#   characters (repaired 2026-10-10). Both halves must share one codec.
$Utf8 = New-Object System.Text.UTF8Encoding($false)

$VersionFile = Join-Path $Root 'VERSION'
if (-not (Test-Path $VersionFile)) {
    Write-Host "ERROR: VERSION file not found at $VersionFile" -ForegroundColor Red
    exit 1
}
$Authority = ([System.IO.File]::ReadAllText($VersionFile, $Utf8)).Trim()

if (-not $Version) { $Version = $Authority }

if ($Version -notmatch '^\d+\.\d+\.\d+$') {
    Write-Host "ERROR: version must be MAJOR.MINOR.PATCH (got '$Version')" -ForegroundColor Red
    exit 1
}

# =============================================================================
# The surfaces - every OTHER place this repo stores its number
# =============================================================================
# version-info.txt is deliberately absent: the build writes it from VERSION.
# A surface is STALE when applying Rep to the file changes it.

$Surfaces = @()
if (Test-Path (Join-Path $Root 'pyproject.toml')) {
    $Surfaces += @{ Path = 'pyproject.toml'
                    Rx   = '(?m)^version\s*=\s*"[^"]*"'
                    Rep  = 'version = "{V}"' }
}
if (Test-Path (Join-Path $Root 'uv.lock')) {
    # uv.lock's own entry for THIS project. `uv sync` regenerates the file, but
    # keeping the entry in step here means a bump never leaves a dirty lock.
    $Surfaces += @{ Path = 'uv.lock'
                    Rx   = '(?m)^(name = "' + [regex]::Escape($RepoName) + '"\r?\nversion = )"[^"]*"'
                    Rep  = '$1"{V}"' }
}

function Get-SurfaceText {
    param($S)
    $p = Join-Path $Root $S.Path
    if (-not (Test-Path $p)) { return $null }
    return ([System.IO.File]::ReadAllText($p, $Utf8))
}

function Get-SurfaceCurrent {
    param($S)
    $text = Get-SurfaceText $S
    if ($null -eq $text) { return '<file missing>' }
    $rx = [regex]$S.Rx
    if ($rx.IsMatch($text)) { return $rx.Match($text).Value.Trim() }
    return '<pattern not found>'
}

function Set-SurfaceValue {
    param($S, [string]$Rep)
    $p = Join-Path $Root $S.Path
    $text = [System.IO.File]::ReadAllText($p, $Utf8)
    $rx = [regex]$S.Rx
    if ($rx.IsMatch($text)) { return $rx.Replace($text, $Rep, 1) }
    return $null
}

# =============================================================================
# Show
# =============================================================================

if ($Show) {
    Write-Host ""
    Write-Host "  $RepoName version surfaces  (authority: VERSION = $Authority)" -ForegroundColor Cyan
    Write-Host "  ------------------------------------------------------------------"
    Write-Host ("  {0,-40} {1}" -f 'VERSION', $Authority)
    foreach ($s in $Surfaces) {
        Write-Host ("  {0,-40} {1}" -f $s.Path, (Get-SurfaceCurrent $s))
    }
    Write-Host ""
    return
}

# =============================================================================
# Check
# =============================================================================

if ($Check) {
    $stale = @()
    if ($Authority -ne $Version) {
        $stale += "VERSION -> '$Authority' (want '$Version')"
    }
    foreach ($s in $Surfaces) {
        $text = Get-SurfaceText $s
        if ($null -eq $text) { $stale += "$($s.Path)  <file missing>"; continue }
        $rep = $s.Rep.Replace('{V}', $Version)
        $new = Set-SurfaceValue $s $rep
        if ($null -eq $new) { $stale += "$($s.Path)  <pattern not found>"; continue }
        if ($new -ne $text) {
            $stale += ("{0}  now: {1}" -f $s.Path, (Get-SurfaceCurrent $s))
        }
    }

    Write-Host ""
    if ($stale.Count -eq 0) {
        Write-Host "  $RepoName VERSION CHECK OK - all surfaces at $Version" -ForegroundColor Green
        Write-Host ""
        exit 0
    }
    Write-Host "  $RepoName VERSION CHECK FAILED - $($stale.Count) surface(s) disagree with $Version" -ForegroundColor Red
    foreach ($x in $stale) { Write-Host "    - $x" -ForegroundColor Red }
    Write-Host ""
    Write-Host "  Fix:  ./Set-Version.ps1 $Version" -ForegroundColor Yellow
    Write-Host ""
    exit 1
}

# =============================================================================
# Write
# =============================================================================

Write-Host ""
Write-Host "  Setting $RepoName version to $Version  (was $Authority)" -ForegroundColor Cyan
Write-Host ""

$touched = @()
$failed  = @()

if ($Authority -ne $Version) {
    [System.IO.File]::WriteAllText($VersionFile, $Version, $Utf8)
    Write-Host ("  {0,-40} {1}" -f 'VERSION', $Version)
    $touched += 'VERSION'
} else {
    Write-Host ("  {0,-40} {1}" -f 'VERSION', "$Version  (unchanged)")
}

foreach ($s in $Surfaces) {
    $text = Get-SurfaceText $s
    if ($null -eq $text) { $failed += "$($s.Path)  <file missing>"; continue }
    $rep = $s.Rep.Replace('{V}', $Version)
    $new = Set-SurfaceValue $s $rep
    if ($null -eq $new) { $failed += "$($s.Path)  <pattern not found>"; continue }
    if ($new -eq $text) {
        Write-Host ("  {0,-40} {1}" -f $s.Path, "unchanged")
        continue
    }
    # NOTE: byte-level write, to preserve the file's own line endings.
    [System.IO.File]::WriteAllText((Join-Path $Root $s.Path), $new, $Utf8)
    Write-Host ("  {0,-40} {1}" -f $s.Path, "-> $Version") -ForegroundColor Green
    if ($touched -notcontains $s.Path) { $touched += $s.Path }
}

Write-Host ""
if ($failed.Count -gt 0) {
    Write-Host "  WARNING - $($failed.Count) surface(s) could not be located:" -ForegroundColor Yellow
    foreach ($x in $failed) { Write-Host "    - $x" -ForegroundColor Yellow }
    Write-Host ""
}

if ($Commit -and $touched.Count -gt 0) {
    Write-Host "  Committing $($touched.Count) file(s)..." -ForegroundColor Cyan
    Push-Location $Root
    # explicit paths only - never 'git add -A'
    & git add -- $touched
    & git commit -m "Bump $RepoName to $Version"
    Pop-Location
}

Write-Host "  Done. $RepoName is at $Version." -ForegroundColor Cyan
Write-Host ""
